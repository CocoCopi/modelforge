package com.modelforge.app.cloud

import com.modelforge.app.data.ModelManifest

/**
 * Generates a ready-to-run Colab notebook for one model.
 *
 * The notebook builds the *same* C++ engine the phone uses, trains on the
 * exported token cache, and mirrors progress.json plus checkpoints back into a
 * Google Drive folder. It contains no credentials and no hidden endpoints: the
 * user runs each cell in their own Colab session, under their own quota.
 */
object ColabNotebook {

    const val REPO_URL = "https://github.com/CocoCopi/ModelForge.git"

    fun notebook(manifest: ModelManifest): String {
        val settings = manifest.settings
        val folder = "ModelForge/${manifest.id}"
        val cells = ArrayList<String>()

        cells += markdown(
            """
            # ModelForge · ${manifest.name}

            Cloud training for **${manifest.name}** (series version ${manifest.seriesVersion}).

            This notebook was generated by ModelForge on your phone. It builds the same C++
            engine, reads the exported `tokens.bin`, and writes checkpoints you can import back
            into the app.

            **Pick a CPU runtime.** The engine is CPU-only, so a GPU or TPU runtime will not make
            it faster; a Colab CPU is usually several times faster than a phone CPU. Free Colab
            sessions can be disconnected at any time, so checkpoints are mirrored to Drive.

            1. Upload the exported package to `My Drive/$folder/`.
            2. Run the cells in order.
            3. Import `output/best.mfck` from that folder in ModelForge → Cloud training.
            """.trimIndent()
        )

        cells += code(
            """
            from google.colab import drive
            drive.mount('/content/drive')
            """.trimIndent()
        )

        cells += code(
            """
            import os, shutil, subprocess, threading, time
            from pathlib import Path

            PACKAGE = Path('/content/drive/MyDrive/$folder')
            WORK = Path('/content/mf-work')
            OUT = WORK / 'out'
            SYNC = PACKAGE / 'output'
            for path in (WORK, OUT):
                path.mkdir(parents=True, exist_ok=True)
            SYNC.mkdir(parents=True, exist_ok=True)
            assert (PACKAGE / 'input' / 'tokens.bin').is_file(), \
                'Upload the exported package to My Drive/$folder first.'
            print('Package found:', PACKAGE)
            """.trimIndent()
        )

        cells += code(
            """
            # Build the training driver from the public ModelForge source.
            if not Path('/content/ModelForge').exists():
                subprocess.run(['git', 'clone', '--depth', '1', '$REPO_URL', '/content/ModelForge'], check=True)
            subprocess.run(['cmake', '-S', '/content/ModelForge/app/src/main/cpp',
                            '-B', '/content/mf-build', '-DCMAKE_BUILD_TYPE=Release'], check=True)
            subprocess.run(['cmake', '--build', '/content/mf-build', '--target', 'mf_train', '-j', '2'], check=True)
            print('Engine built.')
            """.trimIndent()
        )

        cells += code(
            """
            # Local disks are much faster than Drive for the training loop.
            shutil.copytree(PACKAGE / 'input', WORK / 'input', dirs_exist_ok=True)
            print('Inputs copied:', list((WORK / 'input').iterdir()))
            """.trimIndent()
        )

        cells += code(
            """
            STEPS = ${settings.steps}
            command = [
                '/content/mf-build/mf_train',
                '--tokens', str(WORK / 'input' / 'tokens.bin'),
                '--config', str(WORK / 'input' / 'config.json'),
                '--out', str(OUT),
                '--steps', str(STEPS),
                '--batch', '${settings.batchSize}',
                '--seq', '${settings.seqLength}',
                '--lr', '${settings.learningRate}',
                '--wd', '${settings.weightDecay}',
                '--warmup', '${settings.warmupSteps}',
                '--every', '${settings.checkpointEvery}',
            ]
            if (WORK / 'input' / 'init.mfck').is_file():
                command += ['--init', str(WORK / 'input' / 'init.mfck')]

            stop_sync = threading.Event()
            def mirror():
                while not stop_sync.wait(120):
                    try:
                        for name in ('progress.json', 'last.mfck', 'best.mfck'):
                            src = OUT / name
                            if src.is_file():
                                shutil.copy(src, SYNC / (name + '.tmp'))
                                os.replace(SYNC / (name + '.tmp'), SYNC / name)
                    except Exception as exc:
                        print('Sync retry:', exc)

            sync_thread = threading.Thread(target=mirror, daemon=True)
            sync_thread.start()
            print('Running:', ' '.join(command))
            try:
                with open(OUT / 'train.log', 'w') as log:
                    process = subprocess.Popen(command, stdout=subprocess.PIPE,
                                               stderr=subprocess.STDOUT, text=True)
                    for line in process.stdout:
                        print(line, end='')
                        log.write(line)
                        log.flush()
                    code = process.wait()
            finally:
                stop_sync.set()
                sync_thread.join(timeout=5)
            print('Exit code:', code)
            """.trimIndent()
        )

        cells += code(
            """
            # Final mirror: these are the files ModelForge imports.
            for name in ('progress.json', 'last.mfck', 'best.mfck', 'train.log'):
                src = OUT / name
                if src.is_file():
                    shutil.copy(src, SYNC / name)
            print('Synced to Drive:', list(SYNC.iterdir()))
            print('In ModelForge, open Cloud training → Import cloud checkpoint and choose output/best.mfck.')
            """.trimIndent()
        )

        return buildString {
            append("{\n")
            append("  \"nbformat\": 4,\n  \"nbformat_minor\": 5,\n")
            append("  \"metadata\": {\n")
            append("    \"colab\": { \"name\": ")
            append(jsonQuote("ModelForge · ${manifest.name}"))
            append(", \"provenance\": [] },\n")
            append("    \"kernelspec\": { \"name\": \"python3\", \"display_name\": \"Python 3\" }\n")
            append("  },\n")
            append("  \"cells\": [\n")
            append(cells.joinToString(",\n"))
            append("\n  ]\n}\n")
        }
    }

    /** JSON string escaping without org.json, so the generator is testable on the JVM. */
    internal fun jsonQuote(value: String): String = buildString(value.length + 2) {
        append('"')
        value.forEach { char ->
            when (char) {
                '"' -> append("\\\"")
                '\\' -> append("\\\\")
                '\n' -> append("\\n")
                '\r' -> append("\\r")
                '\t' -> append("\\t")
                '\b' -> append("\\b")
                '\u000C' -> append("\\f")
                else -> if (char < ' ') append("\\u%04x".format(char.code)) else append(char)
            }
        }
        append('"')
    }

    private fun markdown(text: String): String = cell(text, markdown = true)

    private fun code(text: String): String = cell(text, markdown = false)

    private fun cell(text: String, markdown: Boolean): String {
        val lines = text.lines().mapIndexed { index, line ->
            jsonQuote(if (index < text.lines().lastIndex) "$line\n" else line)
        }
        return buildString {
            append("    {\n")
            append("      \"cell_type\": ")
            append(jsonQuote(if (markdown) "markdown" else "code"))
            append(",\n      \"metadata\": {},\n")
            if (!markdown) {
                append("      \"execution_count\": null,\n      \"outputs\": [],\n")
            }
            append("      \"source\": [")
            append(lines.joinToString(", "))
            append("]\n    }")
        }
    }
}
